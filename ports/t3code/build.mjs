// Generates fall.json, a T3 Code theme file (Settings → Appearance → Create theme → Import,
// or publish it into ~/.t3/userdata/themes/).
import { emit, loadPalette, mix } from "../../lib/palette.mjs";

const { name, appearance, swatches, syntax, editor } = loadPalette();

const bg = editor.background;
const fg = editor.foreground;
const muted = syntax.punctuation;
const accent = swatches.pink;
const sidebar = mix(bg, "#000000", 0.2);
const surface = mix(bg, fg, 0.04);
const border = mix(bg, fg, 0.12);
const tint = (color, amount = 0.15) => mix(bg, color, amount);

// Fall avoids blue light, so T3 Code's blue "update" and "focus" roles take Fall hues instead.
const colors = {
  canvas: bg,
  chrome: bg,
  toolbar: bg,
  toolbarForeground: fg,
  toolbarBorder: border,
  toolbarControl: surface,
  toolbarControlForeground: fg,
  toolbarControlHover: mix(bg, fg, 0.08),
  surface,
  surfaceRaised: mix(bg, fg, 0.06),
  surfaceOverlay: mix(bg, fg, 0.08),
  text: fg,
  textMuted: muted,
  border,
  input: mix(bg, fg, 0.16),
  focus: accent,
  accent,
  accentForeground: bg,
  secondary: surface,
  secondaryForeground: fg,
  muted: surface,
  mutedForeground: muted,
  placeholder: muted,
  secondaryLabel: muted,
  iconMuted: muted,
  error: editor.removed,
  errorForeground: editor.removed,
  errorSurface: tint(editor.removed),
  warning: swatches.lightOrange,
  warningForeground: swatches.lightOrange,
  warningSurface: tint(swatches.lightOrange),
  update: swatches.purple,
  updateForeground: swatches.purple,
  updateSurface: tint(swatches.purple),
  accentSurface: tint(accent, 0.14),
  accentSurfaceForeground: fg,
  messageSurface: tint(accent, 0.1),
  messageForeground: fg,
  messageAction: accent,
  messageActionForeground: bg,
  messageActionHover: mix(accent, fg, 0.25),
  codeBackground: sidebar,
  codeForeground: fg,
  searchMatchBackground: tint(swatches.lightOrange, 0.35),
  searchMatchForeground: fg,
  searchMatchActiveBackground: swatches.lightOrange,
  searchMatchActiveForeground: bg,
  sidebar,
  sidebarForeground: fg,
  sidebarMutedForeground: muted,
  sidebarControlSurface: mix(sidebar, fg, 0.04),
  sidebarRowHover: mix(sidebar, fg, 0.05),
  sidebarRowActive: mix(sidebar, fg, 0.09),
  sidebarRowSelected: mix(sidebar, fg, 0.07),
  sidebarBorder: mix(sidebar, fg, 0.08),
  terminalBackground: bg,
  terminalForeground: fg,
  terminalCursor: editor.cursor,
  terminalSelection: editor.selection,
  terminalScrollbar: border,
  terminalScrollbarHover: mix(bg, fg, 0.2),
};

// T3 Code highlights chat code with its Highlights lexers and the fixed pierre-dark palette, and
// writes each token's color inline. Key: pierre-dark's color. Value: the Fall syntax role for the
// tokens it colors. Spans carry nothing but the color, so Fall's green definition keywords cannot
// be told apart from other keywords here.
const PIERRE_DARK_TOKENS = {
  "#FF678D": "keyword", // keyword, storage
  "#FF855E": "keyword", // entity.name.tag (Fall colors tags like keywords)
  "#08C0EF": "keyword", // arithmetic, logical, and comparison operators
  "#737373": "comment",
  "#5ECC71": "string",
  "#64D1DB": "string", // string.regexp
  "#68CDF2": "constant", // numbers, booleans
  "#FFD452": "constant",
  "#61D5C0": "constant", // escapes
  "#FFAB16": "parameter", // this, self, namespaces
  "#A3A3A3": "parameter",
  "#60D199": "parameter", // attribute names
  "#9D6AFB": "function",
  "#D568EA": "function", // types and classes
  "#69B1FF": "important", // decorators
  "#FFA359": "text", // plain variables and object keys
  "#FAFAFA": "text",
  "#636363": "punctuation",
};

const tokenRules = Object.entries(PIERRE_DARK_TOKENS).map(([pierre, role]) => {
  const italic = role === "comment" ? " font-style: italic;" : "";
  return `.dark .chat-markdown-shiki [style*="color:${pierre}" i] { color: ${syntax[role]} !important;${italic} }`;
});

const theme = {
  version: 1,
  id: "fall",
  name,
  appearance,
  colors,
  css: `/* Fall syntax colors for chat code blocks. Generated by ports/t3code/build.mjs. */\n${tokenRules.join("\n")}\n`,
};

emit(new URL("./fall.json", import.meta.url), `${JSON.stringify(theme, null, 2)}\n`);
